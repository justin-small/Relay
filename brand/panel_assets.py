#!/usr/bin/env python3
"""Write the panel firmware's boot-logo images.  python3 brand/panel_assets.py
Two alpha-only (A8) pictures the firmware tints itself: the caption bubble and the word "relay", both drawn
for a lockup 384 by 112 pixels. Output: firmware/relay-display/main/boot_logo.c. Needs Google Chrome and Pillow."""
import pathlib, subprocess, tempfile
from PIL import Image
import marks as M

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "firmware/relay-display/main/boot_logo.c"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
H = 112; S = 0.62
WX, WY = 62.5 + 19 + 4.5 * S, 32 - 20 * S
LOCK_W = WX + (M.WORD_W - 4.5) * S + 2
W = round(LOCK_W * H / 64)                     # 384
# Where each picture sits in the lockup, in pixels: x, y, width, height. boot_view.cpp holds the same numbers.
BUBBLE = (35, 10, 75, 96)
WORD = (142, 0, W - 142, H)

def lockup(body):
    return f'<svg style="display:block" width="{W}" height="{H}" viewBox="0 0 {LOCK_W:.1f} 64">{body}</svg>'

bubble = f'<g transform="translate(-15.3 -14.55) scale(1.4545)"><path fill="#fff" d="{M.BUBBLE}"/></g>'
word = M.wordmark("#fff", WX, WY, S)
tmp = pathlib.Path(tempfile.mkdtemp()); html = tmp / "a.html"; png = tmp / "a.png"
html.write_text(f'<body style="margin:0;background:#000">{lockup(bubble)}{lockup(word)}</body>')
subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                "--window-size=800,480", f"--screenshot={png}", html.as_uri()], check=True, capture_output=True)
sheet = Image.open(png).convert("L")

def cut(box, row):
    x, y, w, h = box
    return sheet.crop((x, row * H + y, x + w, row * H + y + h))

def c_array(name, im):
    w, h = im.size; px = im.tobytes()
    rows = "\n".join("    " + ",".join(str(b) for b in px[r * w:(r + 1) * w]) + "," for r in range(h))
    return (f"static const uint8_t {name}_map[] = {{\n{rows}\n}};\n\n"
            f"const lv_image_dsc_t {name} = {{\n"
            f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = {w}, .h = {h}, .stride = {w}}},\n"
            f"    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n")

b, wd = cut(BUBBLE, 0), cut(WORD, 1)
assert b.getbbox() and wd.getbbox(), "a picture came out empty"
# nothing may touch the crop's edge, or the crop is cutting the drawing
full_b, full_w = sheet.crop((0, 0, W, H)).getbbox(), sheet.crop((0, H, W, 2 * H)).getbbox()
assert full_b[0] >= BUBBLE[0] and full_b[1] >= BUBBLE[1] and full_b[2] <= BUBBLE[0] + BUBBLE[2] and full_b[3] <= BUBBLE[1] + BUBBLE[3], full_b
assert full_w[0] >= WORD[0] and full_w[2] <= W, full_w
OUT.write_text(
    "// The boot picture's two images (boot_view.cpp): the caption bubble and the word \"relay\", as alpha only, so the\n"
    "// firmware gives each its colour. GENERATED by brand/panel_assets.py from the logo's drawing (brand/marks.py).\n"
    "// Do not edit by hand: change the drawing and run the script.\n"
    '#include "lvgl.h"\n\n' + c_array("relay_boot_bubble", b) + "\n" + c_array("relay_boot_word", wd))
print(f"{OUT.name}: bubble {b.size} ink {full_b}, word {wd.size} ink {full_w}, {OUT.stat().st_size // 1024} KB of source")
